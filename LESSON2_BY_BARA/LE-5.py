#TRANSFORMATION

#INDEXING & SLICING

text = "Python"

#extract the first character

print (text[0])
print (text[-6]) #negative indexing

#EXTRACT THE LAST CHARACTER
print (text[5])
print (text[-1]) #negative indexing

#extract y
print (text[1])

#SELECTIVE SLICING

date = "2026-01-28"

#get the first 4 values
print(date[0:4])
print(date[:4])

#get the last 2 values.
print(date[8:10])
print(date[-2:])
